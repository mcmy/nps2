type I18nValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (source: string) => string;
};

const I18nContext = createContext<I18nValue>({ language: 'zh', setLanguage: () => {}, t: source => source });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    if (typeof localStorage !== 'undefined') return localStorage.getItem('nps-language') === 'en' ? 'en' : 'zh';
    return 'zh';
  });
  useEffect(() => {
    document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
    localStorage.setItem('nps-language', language);
  }, [language]);
  const value = useMemo<I18nValue>(() => ({ language, setLanguage, t: source => language === 'en' ? english[source] || source : source }), [language]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
